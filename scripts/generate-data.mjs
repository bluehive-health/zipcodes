#!/usr/bin/env node
// Turns data/zipcodes.tsv (the committed source of truth) into src/data.generated.ts,
// a single string constant that the library parses once at load time.
//
// A packed string is ~3x smaller than the equivalent object literal and several
// times faster for the JS engine to load.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('../', import.meta.url);
const tsv = readFileSync(new URL('data/zipcodes.tsv', root), 'utf8');
const [header, ...lines] = tsv.split('\n').filter(Boolean);

if (header !== 'zip\tlatitude\tlongitude\tcity\tstate') {
    throw new Error(`Unexpected header in data/zipcodes.tsv: ${JSON.stringify(header)}`);
}

lines.forEach((line, i) => {
    const fields = line.split('\t');
    const [zip, lat, lon, city, state] = fields;
    const ok =
        fields.length === 5 &&
        /^\d{5}$/.test(zip) &&
        Number.isFinite(Number(lat)) &&
        Number.isFinite(Number(lon)) &&
        city.length > 0 &&
        !/[|;]/.test(city) &&
        /^[A-Z]{2}$/.test(state);
    if (!ok) {
        throw new Error(`Bad record on line ${i + 2} of data/zipcodes.tsv: ${JSON.stringify(line)}`);
    }
});

const out =
    '// GENERATED by scripts/generate-data.mjs from data/zipcodes.tsv. Do not edit.\n' +
    '/** Records separated by ";", fields by "|": zip, latitude, longitude, city, state. */\n' +
    `export const DATA: string = ${JSON.stringify(lines.map((l) => l.replaceAll('\t', '|')).join(';'))};\n`;

const target = new URL('src/data.generated.ts', root);
writeFileSync(target, out);
console.log(`Wrote ${lines.length} ZIP codes to ${fileURLToPath(target)}`);
